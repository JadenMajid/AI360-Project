#!/usr/bin/env bash
# Mirror the proposal Google Doc (single source of truth) into docs/proposal.md
set -euo pipefail
DOC=1NLqX-EZxLGXhi3cHxwRBW2x9xrznWAKaeRQFit8XFkk
OUT="$(dirname "$0")/../docs/proposal.md"
body=$(curl -fsSL "https://docs.google.com/document/d/$DOC/export?format=md")
printf '<!-- Generated by scripts/sync_proposal.sh. Do not edit; change https://docs.google.com/document/d/%s instead. -->\n\n%s\n' "$DOC" "$body" > "$OUT"
